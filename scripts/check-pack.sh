#!/usr/bin/env bash
# Packs the workspace packages and checks the published manifests. A `workspace:` spec left in
# a published package.json breaks `sf plugins install` for every user, and nothing else in the
# build would notice. Also checks DuckDB stays confined to the query plugin and pinned exactly.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

cd "$root"
pnpm --filter @cclabsnz/sf-evidence-engine pack --pack-destination "$tmp" >/dev/null
pnpm --filter @cclabsnz/sf-evidence pack --pack-destination "$tmp" >/dev/null
pnpm --filter @cclabsnz/sf-evidence-query pack --pack-destination "$tmp" >/dev/null

engine_version="$(node -p "require('./packages/sf-evidence-engine/package.json').version")"
engine_tarball="$(ls "$tmp"/cclabsnz-sf-evidence-engine-[0-9]*.tgz)"
cli_tarball="$(ls "$tmp"/cclabsnz-sf-evidence-[0-9]*.tgz)"
query_tarball="$(ls "$tmp"/cclabsnz-sf-evidence-query-[0-9]*.tgz)"
tar -xOf "$engine_tarball" package/package.json > "$tmp/engine-package.json"
tar -xOf "$cli_tarball" package/package.json > "$tmp/cli-package.json"
tar -xOf "$query_tarball" package/package.json > "$tmp/query-package.json"

# The query plugin's oclif.manifest.json is generated by prepack; sf installs it as a JIT plugin
# and reads commands from the manifest, so a tarball without it has no commands.
# Listed to a file, not piped: `grep -q` exits on the first match, tar then dies of SIGPIPE,
# and under pipefail that reads as "manifest missing" (seen on Linux CI, not on macOS).
tar -tf "$query_tarball" > "$tmp/query-files.txt"
if ! grep -qx 'package/oclif.manifest.json' "$tmp/query-files.txt"; then
  echo 'query tarball is missing oclif.manifest.json'
  exit 1
fi

node - "$tmp" "$engine_version" <<'NODE'
const [tmp, engineVersion] = process.argv.slice(2);
const read = (name) => require('node:fs').readFileSync(`${tmp}/${name}-package.json`, 'utf8');
const fail = (msg) => {
  console.error(msg);
  process.exit(1);
};

for (const name of ['cli', 'query']) {
  const raw = read(name);
  if (raw.includes('workspace:')) fail(`packed ${name} package.json still contains a workspace: specifier`);
  const range = JSON.parse(raw).dependencies?.['@cclabsnz/sf-evidence-engine'];
  if (range !== `^${engineVersion}`) {
    fail(`expected ${name} @cclabsnz/sf-evidence-engine ^${engineVersion}, found ${range}`);
  }
}

const duckdb = JSON.parse(read('query')).dependencies?.['@duckdb/node-api'];
if (duckdb !== '1.5.6-r.2') fail(`expected query @duckdb/node-api 1.5.6-r.2 (exact), found ${duckdb}`);

for (const name of ['engine', 'cli']) {
  if (read(name).includes('@duckdb/')) fail(`packed ${name} package.json mentions @duckdb/`);
}
NODE

echo "pack ok"
