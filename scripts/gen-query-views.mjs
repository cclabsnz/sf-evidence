#!/usr/bin/env node
// Renders docs/query-views.md, the data dictionary for the `sf evidence query` views, from the
// same VIEWS definitions the query plugin compiles into DuckDB, so the dictionary cannot drift
// from the views. A test regenerates it and string-compares. Needs the engine built
// (`pnpm -r build`).
//
//   node scripts/gen-query-views.mjs            write docs/query-views.md
//   node scripts/gen-query-views.mjs --stdout   print it instead
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { VIEWS } = await import(pathToFileURL(resolve(root, 'packages/sf-evidence-engine/lib/index.js')).href);

/** A table cell: pipes escaped, line breaks flattened. */
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

function render() {
  const out = [];
  out.push('# Query views');
  out.push('');
  out.push(
    'Generated by `scripts/gen-query-views.mjs` from the view definitions `sf evidence query` ' +
      'compiles. Do not edit by hand: a test regenerates it and fails on any difference.',
  );
  out.push('');
  for (const v of VIEWS) {
    out.push(`## ${v.name}`);
    out.push('');
    out.push(`Version ${v.version}. Grain: ${v.grain}`);
    out.push('');
    out.push(v.description);
    out.push('');
    out.push(`Sources: ${v.sources.map((s) => `\`${s}\``).join(', ')}.`);
    out.push('');
    out.push(`Time column: \`${v.timeColumn}\``);
    out.push('');
    out.push('| name | type | description |');
    out.push('| --- | --- | --- |');
    for (const c of v.columns) out.push(`| \`${c.name}\` | \`${cell(c.type)}\` | ${cell(c.description)} |`);
    out.push('');
    out.push('### Known gaps');
    out.push('');
    if (v.knownGaps.length === 0) out.push('None recorded.');
    else for (const g of v.knownGaps) out.push(`- ${g}`);
    out.push('');
  }
  return out.join('\n');
}

const text = `${render().trimEnd()}\n`;
if (process.argv.includes('--stdout')) process.stdout.write(text);
else writeFileSync(resolve(root, 'docs/query-views.md'), text);
