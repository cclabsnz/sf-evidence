#!/usr/bin/env node
// Renders docs/security-statement.md from the same buildExplanation that `sf evidence explain`
// prints, so the published statement cannot drift from the code. A test regenerates it and
// string-compares. Needs the engine built (`pnpm -r build`).
//
//   node scripts/gen-security-statement.mjs            write docs/security-statement.md
//   node scripts/gen-security-statement.mjs --stdout   print it instead
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const engine = await import(pathToFileURL(resolve(root, 'packages/sf-evidence-engine/lib/index.js')).href);
const { buildExplanation, COLLECTORS, LocalSink, GitSink } = engine;

const INSTANCE_URL = 'https://<your-org>.my.salesforce.com';
const ARCHIVE = './sf-evidence-archive';

const WINDOW_NOTE =
  'The audit-trail and login-history <from> and <to> are the collection window, sliced and narrowed on timeout.';

const sources = Object.keys(COLLECTORS);
const sinkSets = [
  ['local', new LocalSink(ARCHIVE)],
  ['git', new GitSink(ARCHIVE, {})],
];

function render() {
  const out = [];
  out.push('# Security statement');
  out.push('');
  out.push(
    'Generated by `scripts/gen-security-statement.mjs` from the same code `sf evidence explain` ' +
      'runs. Do not edit by hand: a test regenerates it and fails on any difference.',
  );
  out.push('');
  out.push(`Sources covered: ${sources.map((s) => `\`${s}\``).join(', ')}.`);
  out.push('');

  const first = buildExplanation({ sources, sinks: [sinkSets[0][1]], instanceUrl: INSTANCE_URL });
  out.push('## Queries');
  out.push('');
  out.push('These are the same for every sink.');
  out.push('');
  for (const q of first.queries) {
    const scope = q.scope === 'plugin' ? ' [plugin, not a collector]' : '';
    out.push(`- \`${q.object}\`${scope}, requires: ${q.permission}`);
    out.push('');
    out.push('  ```text');
    out.push(`  ${q.soql}`);
    out.push('  ```');
    out.push('');
    if (q.note) {
      out.push(`  When: ${q.note}`);
      out.push('');
    }
  }
  out.push(WINDOW_NOTE);
  out.push('');

  for (const [id, sink] of sinkSets) {
    const e = buildExplanation({ sources, sinks: [sink], instanceUrl: INSTANCE_URL });
    out.push(`## Sink: ${id}`);
    out.push('');
    out.push('### File writes');
    out.push('');
    for (const w of e.writes) out.push(w.startsWith('  ') ? `- ${w.trim()}` : `- ${w}`);
    out.push('');
    out.push('### Network destinations');
    out.push('');
    for (const d of e.destinations) {
      out.push(`- \`${d.protocol}://${d.host}\``);
      out.push(`  - Purpose: ${d.purpose}`);
      out.push(`  - Credential: ${d.credentialSource}`);
    }
    out.push('');
    out.push('### What this plugin does not do');
    out.push('');
    for (const a of e.assertions) {
      out.push(`- ${a.claim}`);
      out.push(`  - Mechanism: ${a.mechanism}`);
    }
    out.push('');
  }
  return out.join('\n');
}

const text = `${render().trimEnd()}\n`;
if (process.argv.includes('--stdout')) process.stdout.write(text);
else writeFileSync(resolve(root, 'docs/security-statement.md'), text);
